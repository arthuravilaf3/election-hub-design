// One-time build script: converts us-atlas TopoJSON (pre-projected albersUsa,
// 975x610 viewBox with AK/HI insets) into a static TypeScript module of SVG
// path strings. Run with: npm run generate:map
// d3/topojson are dev-only dependencies — nothing from this pipeline ships at runtime.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { feature } from 'topojson-client';
import { geoPath } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = require('us-atlas/states-albers-10m.json');

// FIPS -> USPS postal code for the 50 states + DC (territories excluded).
const FIPS_TO_POSTAL = {
  '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO',
  '09': 'CT', '10': 'DE', '11': 'DC', '12': 'FL', '13': 'GA', '15': 'HI',
  '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY',
  '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN',
  '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE', '32': 'NV', '33': 'NH',
  '34': 'NJ', '35': 'NM', '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH',
  '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI', '45': 'SC', '46': 'SD',
  '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA',
  '54': 'WV', '55': 'WI', '56': 'WY',
};

// Data is pre-projected, so geoPath with no projection emits path data as-is.
const path = geoPath();
const features = feature(topo, topo.objects.states).features;

const states = features
  .filter((f) => FIPS_TO_POSTAL[f.id])
  .map((f) => ({
    id: FIPS_TO_POSTAL[f.id],
    name: f.properties.name,
    d: path(f),
  }))
  // Alphabetical by name: this becomes DOM order, and therefore tab order.
  .sort((a, b) => a.name.localeCompare(b.name));

if (states.length !== 51) {
  throw new Error(`Expected 51 states (50 + DC), got ${states.length}`);
}

const out = `// GENERATED by scripts/generate-map.mjs — do not edit by hand.
// Pre-projected albersUsa geometry (us-atlas states-albers-10m), viewBox 0 0 975 610.
// Order is alphabetical by state name; the map renders in this order, which
// makes keyboard tab order predictable for screen reader and keyboard users.

export interface StateShape {
  id: string;   // USPS postal code, e.g. 'GA'
  name: string; // 'Georgia'
  d: string;    // SVG path data
}

export const MAP_VIEWBOX = '0 0 975 610';

export const STATE_SHAPES: StateShape[] = ${JSON.stringify(states, null, 2)};
`;

const dest = join(dirname(fileURLToPath(import.meta.url)), '../src/data/states.ts');
writeFileSync(dest, out);
console.log(`Wrote ${states.length} states to src/data/states.ts`);
